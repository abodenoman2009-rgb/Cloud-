import { createReadStream, createWriteStream, promises as fs } from "node:fs";
import path from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";

/**
 * Object storage abstraction.
 *
 * `s3`   — real cloud storage (Amazon S3, Cloudflare R2, Google Cloud Storage
 *          XML API, MinIO…). Selected when STORAGE_DRIVER=s3 and credentials
 *          are present.
 * `local`— durable server-side object volume (DATA_DIR). Never the phone:
 *          files live on the server and follow the user across devices.
 */

export type PutResult = { key: string; size: number };
export type GetResult = { stream: Readable; size: number } | null;

export interface ObjectStore {
  driver: "s3" | "local";
  label: string;
  put(key: string, body: Buffer | Readable, contentType: string, size?: number): Promise<PutResult>;
  head(key: string): Promise<{ size: number } | null>;
  get(key: string, range?: { start: number; end: number }): Promise<GetResult>;
  remove(key: string): Promise<void>;
}

function s3Config() {
  return {
    bucket: process.env.S3_BUCKET?.trim() ?? "",
    client: new S3Client({
      region: process.env.S3_REGION?.trim() || "auto",
      endpoint: process.env.S3_ENDPOINT?.trim() || undefined,
      forcePathStyle: (process.env.S3_FORCE_PATH_STYLE ?? "true") !== "false",
      credentials: {
        accessKeyId: process.env.S3_ACCESS_KEY_ID?.trim() ?? "",
        secretAccessKey: process.env.S3_SECRET_ACCESS_KEY?.trim() ?? "",
      },
    }),
  };
}

function s3Ready(): boolean {
  return Boolean(
    process.env.S3_BUCKET?.trim() &&
      process.env.S3_ACCESS_KEY_ID?.trim() &&
      process.env.S3_SECRET_ACCESS_KEY?.trim(),
  );
}

class S3Store implements ObjectStore {
  driver = "s3" as const;
  label = "S3 Compatible Cloud";
  private cfg = s3Config();

  async put(key: string, body: Buffer | Readable, contentType: string, size?: number): Promise<PutResult> {
    await this.cfg.client.send(
      new PutObjectCommand({
        Bucket: this.cfg.bucket,
        Key: key,
        Body: body,
        ContentType: contentType,
        ...(typeof size === "number" ? { ContentLength: size } : {}),
        ServerSideEncryption: process.env.S3_SSE === "false" ? undefined : "AES256",
      }),
    );
    return { key, size: size ?? 0 };
  }

  async head(key: string): Promise<{ size: number } | null> {
    try {
      const res = await this.cfg.client.send(
        new HeadObjectCommand({ Bucket: this.cfg.bucket, Key: key }),
      );
      return { size: Number(res.ContentLength ?? 0) };
    } catch {
      return null;
    }
  }

  async get(key: string, range?: { start: number; end: number }): Promise<GetResult> {
    try {
      const res = await this.cfg.client.send(
        new GetObjectCommand({
          Bucket: this.cfg.bucket,
          Key: key,
          ...(range ? { Range: `bytes=${range.start}-${range.end}` } : {}),
        }),
      );
      if (!res.Body) return null;
      return {
        stream: res.Body as Readable,
        size: Number(res.ContentLength ?? 0),
      };
    } catch {
      return null;
    }
  }

  async remove(key: string): Promise<void> {
    await this.cfg.client.send(new DeleteObjectCommand({ Bucket: this.cfg.bucket, Key: key }));
  }
}

export function dataDir(): string {
  return path.resolve(process.env.DATA_DIR || path.join(process.cwd(), "data"));
}

/** Keys are generated by the server; still defend against traversal. */
function safePath(key: string): string {
  const base = dataDir();
  const target = path.resolve(base, key);
  if (target !== base && !target.startsWith(base + path.sep)) {
    throw new Error("invalid_storage_key");
  }
  return target;
}

class LocalStore implements ObjectStore {
  driver = "local" as const;
  label = "Server Object Volume";

  async put(key: string, body: Buffer | Readable, contentType: string, size?: number): Promise<PutResult> {
    const target = safePath(key);
    await fs.mkdir(path.dirname(target), { recursive: true });
    const tmp = `${target}.${Date.now()}.tmp`;
    if (Buffer.isBuffer(body)) {
      await fs.writeFile(tmp, body);
    } else {
      await pipeline(body, createWriteStream(tmp));
    }
    await fs.rename(tmp, target);
    const stat = await fs.stat(target);
    void contentType;
    void size;
    return { key, size: stat.size };
  }

  async head(key: string): Promise<{ size: number } | null> {
    try {
      const stat = await fs.stat(safePath(key));
      return { size: stat.size };
    } catch {
      return null;
    }
  }

  async get(key: string, range?: { start: number; end: number }): Promise<GetResult> {
    try {
      const target = safePath(key);
      const stat = await fs.stat(target);
      const stream = createReadStream(target, range ? { start: range.start, end: range.end } : {});
      const size = range ? range.end - range.start + 1 : stat.size;
      return { stream: stream as unknown as Readable, size };
    } catch {
      return null;
    }
  }

  async remove(key: string): Promise<void> {
    try {
      await fs.rm(safePath(key), { force: true });
    } catch {
      /* already gone */
    }
  }
}

let cached: ObjectStore | null = null;

export function getObjectStore(): ObjectStore {
  if (cached) return cached;
  const driver = (process.env.STORAGE_DRIVER || "").toLowerCase();
  cached = driver === "s3" && s3Ready() ? new S3Store() : new LocalStore();
  return cached;
}

export function storageStatus(): { driver: "s3" | "local"; label: string; bucket?: string } {
  const store = getObjectStore();
  return {
    driver: store.driver,
    label: store.label,
    bucket: store.driver === "s3" ? process.env.S3_BUCKET : undefined,
  };
}

/** Object key layout: `u/<userId>/<fileId>` — isolated per user. */
export function objectKey(userId: string, fileId: string): string {
  return `u/${userId}/${fileId}`;
}
